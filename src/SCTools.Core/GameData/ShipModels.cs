    /// The ship a name is: the same name ("Drake Cutlass Black", "cutlass black" without its maker too), else the longest name that is in it, or null.
    /// </summary>
    public static ShipModel? Find(string? name)
    {
        if (string.IsNullOrWhiteSpace(name)) return null;
        var n = Letters(name);
        if (ByName.TryGetValue(n, out var m)) return m;
        var without = All.Where(x => Letters(Without(x.Name)) == n).ToList();   // typed without its maker
        if (without.Count == 1) return without[0];
        return All.Where(x => Letters(Without(x.Name)).Length >= 4 && n.Contains(Letters(Without(x.Name)), StringComparison.Ordinal))
            .OrderByDescending(x => Letters(Without(x.Name)).Length).FirstOrDefault();
    }

    /// <summary>The ship of a class of the game data ("CRUS_Starlifter_C2"), or null.</summary>
    public static ShipModel? OfClass(string? className) => className != null && ByClass.TryGetValue(className, out var m) ? m : null;

    static readonly string[] Makers =
    {
        "Aegis", "Anvil", "Argo", "ARGO", "Banu", "C.O.", "Crusader", "Drake", "Esperia", "Gatac", "Grey's", "Kruger", "MISC", "Mirai", "Origin", "RSI",
        "Vanduul", "Aopoa",
    };

    /// <summary>The name without its maker ("Cutlass Black").</summary>
    public static string Without(string name)
    {
        foreach (var maker in Makers)
            if (name.StartsWith(maker + " ", StringComparison.Ordinal)) return name[(maker.Length + 1)..];
        return name;
    }
